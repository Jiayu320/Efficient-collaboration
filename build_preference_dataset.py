import os
import yaml
import json
import logging
from openai import OpenAI
from tqdm import tqdm
import time
from typing import Dict, Any, List, Tuple

# --- 全局日志记录器 ---
logger = logging.getLogger(__name__)

def setup_logging(log_file: str):
    """配置日志记录器，同时输出到文件和控制台"""
    logging.basicConfig(
        level=logging.INFO,
        format='[%(levelname)s] %(asctime)s %(module)s:%(lineno)d] %(message)s',
        datefmt='%Y-%m-%d %H:%M:%S',
        handlers=[
            logging.FileHandler(log_file, mode='w', encoding='utf-8'),
            logging.StreamHandler()
        ]
    )

def load_yaml_config(path: str) -> Dict[str, Any]:
    """加载 YAML 配置文件"""
    logger.info(f"从 '{path}' 加载配置...")
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return yaml.safe_load(f)
    except Exception as e:
        logger.error(f"无法加载配置文件 {path}: {e}", exc_info=True)
        raise

def load_problems(path: str, limit: int = None) -> List[Dict[str, Any]]:
    """从JSON文件加载问题数据集"""
    logger.info(f"从 '{path}' 加载问题...")
    try:
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        if limit:
            logger.info(f"将问题数量限制为: {limit}")
            return data[:limit]
        return data
    except Exception as e:
        logger.error(f"无法加载数据集 {path}: {e}", exc_info=True)
        raise

def get_api_key(file_path: str) -> str:
    """从文件中安全地获取API密钥"""
    if not file_path or not os.path.exists(file_path):
        logger.warning(f"API密钥文件 '{file_path}' 未找到或未配置。将使用空密钥。")
        return ""
    with open(file_path, 'r') as f:
        return f.read().strip()

def call_planner(client: OpenAI, model: str, problem: str, enable_thinking: bool) -> str:
    """调用Planner模型生成一个解决方案计划"""
    system_prompt = """You are an expert at breaking down complex problems into a step-by-step plan. Your task is to generate a solution plan for the given problem in XML format.

**Instructions:**
1.  The plan must be enclosed in `<Plan>` tags.
2.  The plan must contain between 2 and 10 `<Step>` tags.
3.  Each `<Step>` must have `ID`, `Task`, `Difficulty`, `Token`, and `Rely` attributes.
4.  The `Task` must be a clear, actionable question that ends with a question mark (?).
5.  The final step must provide the conclusive result or final answer.
6.  If a step depends on a previous one, use the `Rely` attribute to list the `ID`s.

### Example
**Problem**: For how many rational numbers between 0 and 1 will $20!$ be the resulting product of their numerator and denominator in lowest terms?
**Plan**:
<Plan>
<Step ID="1" Task="What are the distinct prime factors of 20! ?" Difficulty="4" Token="50" Rely=""/>
<Step ID="2" Task="Count the number of distinct prime factors found in Step 1. Let this count be k. What is the value of k?" Difficulty="2" Token="20" Rely="1"/>
<Step ID="3" Task="The number of pairs of coprime factors (a,b) of 20! is 2^k. The number of rational numbers a/b between 0 and 1 is half of this. Using the formula N = 2^(k-1), what is the final number of such rational numbers?" Difficulty="4" Token="50" Rely="2"/>
</Plan>

Apply the entire framework described above to the problem provided below. 
"""
    
    # 根据配置决定是否移除 <think> 模块的指令
    
        
    user_prompt = f"**Problem**:\n{problem}\n\n**Plan**:"

    logger.info("--- 调用 Planner ---")
    logger.info(f"System Prompt:\n{system_prompt}")
    logger.info(f"User Prompt:\n{user_prompt}")

    try:
        if not enable_thinking:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                temperature=0.9, # 增加一点随机性以获得多样的样本
                max_tokens=1024,
                extra_body={"enable_thinking": False}
            )
        else:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                temperature=0.9, # 增加一点随机性以获得多样的样本
                max_tokens=1024,
                extra_body={"enable_thinking": True}
            )
        plan = response.choices[0].message.content
        logger.info(f"Planner 的输出:\n{plan}")
        return plan
    except Exception as e:
        logger.error(f"调用 Planner API 时出错: {e}", exc_info=True)
        return "" # 返回空字符串表示失败

def call_evaluator(client: OpenAI, model: str, problem: str, plan: str) -> float:
    """调用评估模型为计划打分"""
    system_prompt = """You are an expert AI Systems Analyst specializing in evaluating automated task planning models. Your task is to assess the quality of a solution plan generated by a "Planner" AI. The plan's purpose is to break down a complex problem into a series of executable steps for other AI models.

You will be given the original `Question` and the `Plan` (in XML format) generated by the Planner. Your evaluation must focus on the plan's structural integrity, logical soundness, and suitability for machine execution.

Your final output must be a structured JSON report with a score and a concise justification for each dimension.

-----
## Evaluation Dimensions & Scoring

### 1. Plan Soundness & Decomposition Quality
**Focus:** Does the plan correctly break down the original problem? This is the most critical dimension. A flawed decomposition invalidates the entire plan.
* **Score 1 (Poor):** The plan is fundamentally flawed. It misses critical steps, introduces incorrect logic, or fails to create a path toward the correct solution. The decomposition is illogical or incomplete.
* **Score 3 (Average):** The plan has a viable, high-level strategy but contains minor logical gaps or inefficient steps. It might solve the problem, but not in the most direct or robust way.
* **Score 5 (Excellent):** The plan is a perfect, logical, and efficient decomposition of the problem. Each step is necessary, and together they form the most direct path to the solution.

### 2. Dependency Structure & Logical Flow (`Rely` attribute)
**Focus:** This assesses the correctness of the plan's dependency graph (DAG). A correct structure is essential for efficient parallel execution and providing the right context to Executor models.
* **Score 1 (Poor):** The `Rely` attributes are chaotic. Dependencies are missing for steps that require prior information, or incorrect dependencies create a nonsensical execution order.
* **Score 3 (Average):** The overall flow is mostly correct, but there might be one or two suboptimal dependency links. For example, a step might be unnecessarily sequential when it could be parallel, or it might be missing a minor dependency.
* **Score 5 (Excellent):** The dependency graph is perfect. All dependencies are correctly and minimally specified, maximizing potential parallelism while ensuring every step receives the exact context it needs.

### 3. Task Clarity & Executability (`Task` attribute)
**Focus:** This measures whether each individual `Task` is a clear, unambiguous, and operational instruction for an AI Executor. Vague tasks lead to poor or unpredictable execution.
* **Score 1 (Poor):** Tasks are vague, abstract, or ambiguous (e.g., "Analyze the relationship..."). An Executor model would have to guess the intended operation, likely leading to errors.
* **Score 3 (Average):** Most tasks are clear, but some could be more specific. There might be minor ambiguity that a powerful Executor could potentially overcome, but it's not ideal.
* **Score 5 (Excellent):** Every task is a crystal-clear, operational command. It is a specific, answerable question or a direct instruction for a calculation (e.g., "Calculate the value of P(n) using the recurrence relation from Step 2?"). It is perfectly suited for machine execution.

### 4. Attribute Accuracy (`Difficulty` & `Token` attributes)
**Focus:** This evaluates the planner's ability to accurately estimate the resources required for each task, which is key for your system's dynamic model allocation (small vs. large model).
* **Score 1 (Poor):** The `Difficulty` and `Token` estimates are consistently wrong. Complex reasoning steps are marked as easy, and simple calculations are marked as hard, which would lead to constant misallocation of AI resources.
* **Score 3 (Average):** The estimates are reasonable but lack precision. The general trend (harder tasks get higher scores) is correct, but the specific values might be off, leading to occasional suboptimal model choices.
* **Score 5 (Excellent):** The `Difficulty` and `Token` estimates are highly accurate. The scores correctly reflect the computational and reasoning effort required for each step, enabling precise and efficient model allocation.

### 5. Plan Relevance & Efficiency
**Focus:** This is a check for redundant or irrelevant steps. A good plan is lean and purposeful.
* **Score 1 (Poor):** The plan contains significant redundancy or irrelevant steps that do not contribute to the final solution. It wastes computational resources.
* **Score 3 (Average):** The plan is mostly efficient but includes one or two minor steps that could have been merged or omitted without losing clarity.
* **Score 5 (Excellent):** The plan is maximally efficient. Every single step is necessary and directly contributes to solving the problem. There is no redundancy.

-----
## Final Output Format
Please provide your evaluation in the following structured JSON format. Do not include any text outside of the JSON block.

```json
{
  "evaluationReport": {
    "planSoundnessAndDecomposition": {
      "score": "[Enter a score from 1-5]",
      "justification": "[Your justification here. Explain why you gave this score.]"
    },
    "dependencyStructureAndFlow": {
      "score": "[Enter a score from 1-5]",
      "justification": "[Your justification here. Explain the correctness of the 'Rely' attributes.]"
    },
    "taskClarityAndExecutability": {
      "score": "[Enter a score from 1-5]",
      "justification": "[Your justification here. Assess the ambiguity of the 'Task' attributes.]"
    },
    "attributeAccuracy": {
      "score": "[Enter a score from 1-5]",
      "justification": "[Your justification here. Judge the 'Difficulty' and 'Token' estimates.]"
    },
    "planRelevanceAndEfficiency": {
      "score": "[Enter a score from 1-5]",
      "justification": "[Your justification here. Note any redundant or irrelevant steps.]"
    },
    "overallSummary": "[Provide a final, concise paragraph summarizing the plan's overall quality and its suitability for your multi-agent system. Highlight the most significant strengths and weaknesses.]"
  }
}```"""
    user_prompt = f"**Question:**\n{problem}\n\n**Plan:**\n```xml\n{plan}\n```"

    logger.info("--- 调用 Evaluator ---")
    logger.info(f"System Prompt:\n{system_prompt}")
    logger.info(f"User Prompt:\n{user_prompt}")

    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            response_format={"type": "json_object"},
            temperature=0.0,
            max_tokens=2048
        )
        eval_result_str = response.choices[0].message.content
        logger.info(f"Evaluator 的输出:\n{eval_result_str}")
        
        # 解析JSON并计算总分
        eval_json = json.loads(eval_result_str)
        report = eval_json.get("evaluationReport", {})
        total_score = 0
        for dimension, values in report.items():
            total_score += int(values.get("score", 0))
        
        logger.info(f"评估总分: {total_score}")
        return float(total_score)

    except Exception as e:
        logger.error(f"调用或解析 Evaluator API 时出错: {e}", exc_info=True)
        return -1.0 # 返回一个低分表示评估失败

def main():
    """主函数，用于构建偏好数据集"""
    config = load_yaml_config("dpo_config.yaml")
    setup_logging(config['logging']['log_file'])
    
    # 加载配置
    dataset_cfg = config['dataset']
    planner_cfg = config['planner']
    evaluator_cfg = config['evaluator']

    problems = load_problems(dataset_cfg['input_path'], dataset_cfg.get('limit'))
    
    # 初始化API客户端
    planner_client = OpenAI(
        api_key=get_api_key(planner_cfg.get('key_path')),
        base_url=planner_cfg['base_url']
    )
    evaluator_client = OpenAI(
        api_key=get_api_key(evaluator_cfg['key_path']),
        base_url=evaluator_cfg['base_url']
    )

    preference_data = []
    
    for problem_data in tqdm(problems, desc="正在处理问题"):
        problem_text = problem_data.get("problem") or problem_data.get("question")
        if not problem_text:
            logger.warning(f"跳过一个没有 'problem' 或 'question' 字段的数据项: {problem_data}")
            continue

        logger.info(f"\n{'='*20} 开始处理新问题 {'='*20}")
        logger.info(f"问题: {problem_text[:100]}...")

        samples: List[Tuple[str, float]] = []
        for i in range(planner_cfg['sampling_count']):
            logger.info(f"--- 生成样本 #{i+1}/{planner_cfg['sampling_count']} ---")
            
            plan = call_planner(
                planner_client, 
                planner_cfg['model'], 
                problem_text, 
                planner_cfg['enable_thinking']
            )
            
            if not plan:
                logger.warning("Planner未能生成计划，跳过此样本。")
                continue
            
            # 为避免API调用过于频繁，可以加入短暂延时
            time.sleep(1) 

            score = call_evaluator(
                evaluator_client, 
                evaluator_cfg['model'], 
                problem_text, 
                plan
            )
            samples.append((plan, score))
        
        # 筛选出最佳和最差的计划
        if len(samples) < 2:
            logger.warning(f"问题未能生成足够多的有效样本 (需要>=2, 实际={len(samples)})，跳过。")
            continue

        samples.sort(key=lambda x: x[1], reverse=True)
        
        chosen_plan, chosen_score = samples[0]
        rejected_plan, rejected_score = samples[-1]

        # 确保 chosen 和 rejected 不是完全相同的字符串
        if chosen_plan.strip() == rejected_plan.strip():
            logger.warning("最佳和最差计划完全相同，跳过此问题以避免无效数据。")
            continue
            
        logger.info(f"选择的偏好对: Chosen (得分: {chosen_score}), Rejected (得分: {rejected_score})")

        preference_item = {
            "instruction": problem_text,
            "input": "", # 根据您的格式，input是可选的
            "chosen": chosen_plan,
            "rejected": rejected_plan
        }
        preference_data.append(preference_item)

    # 保存最终的数据集
    output_path = dataset_cfg['output_path']
    logger.info(f"所有问题处理完毕。正在将 {len(preference_data)} 条偏好数据保存到 '{output_path}'...")
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(preference_data, f, indent=2, ensure_ascii=False)
        logger.info("数据集保存成功！")
    except Exception as e:
        logger.error(f"保存数据集时出错: {e}", exc_info=True)

if __name__ == "__main__":
    main()
